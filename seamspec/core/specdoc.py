"""The spec this code has earned: one readable document, generated from the ledger (SPEC §15.2,
ADR-20261011-0995, ADR-20261013-2f6b).

SeamSpec writes no spec up front. What a human approved, rule by rule, *is* the spec; this module
only prints it. Rules of the document:

- **Only what a human approved.** LOCKED rules, the rules they replaced, and active dead ends.
  Proposed and rejected rules are not in it.
- **Built from the committed ledger alone,** so two clones of the same commit print the same
  bytes and a written copy can be checked in CI (`--check`). No timestamps of the run, no local
  journal, no folder names, and no email addresses (the approver's name only).
- **Never edited by hand.** A written copy starts with `GENERATED`; SeamSpec refuses to overwrite a
  file that doesn't.
"""

from __future__ import annotations

from dataclasses import dataclass

from . import adr, verifier
from .area import ROOT_AREA, area
from .models import DeadEnd, Invariant, InvStatus
from .store import Store

GENERATED_PREFIX = "<!-- Generated by `seamspec spec`"
GENERATED = (
    f"{GENERATED_PREFIX} from the SeamSpec ledger (.seamspec/). Do not edit: change the rules, "
    "then run `seamspec spec --out` on this file again. -->"
)
TITLE = "# Spec: what this code guarantees"
VIA = {None: "in the terminal", "terminal": "in the terminal", "chat": "in a chat dialog"}


@dataclass
class Counts:
    rules: int
    retired: int
    dead_ends: int
    proposed: int  # waiting for review: never part of the document

    def line(self) -> str:
        return f"{_n(self.rules, 'rule')} in force, {self.retired} retired, {self.dead_ends} tried and failed"


def _n(count: int, word: str) -> str:
    return f"{count} {word}{'' if count == 1 else 's'}"


def _flat(text: str) -> str:
    return " ".join(text.split())


def _name(approved_by: str | None) -> str:
    """`Maya Chen <maya@example.com>` -> `Maya Chen`: the document may be published; the ledger keeps the rest."""
    who = (approved_by or "").split("<")[0].strip()
    return who or "someone (no name recorded)"


def _paths(paths: list[str]) -> str:
    return ", ".join(f"`{_flat(p)}`" for p in paths)


def _by_area(store: Store, records: list) -> list[tuple[str, list]]:
    groups: dict[str, list] = {}
    for record in records:
        groups.setdefault(area(list(record.scope.paths), store.root), []).append(record)
    return sorted(groups.items(), key=lambda item: (item[0] == ROOT_AREA, item[0]))


def _load(store: Store) -> tuple[list[Invariant], list[Invariant], list[DeadEnd], int]:
    invs = [i for i in store.load_all("inv") if isinstance(i, Invariant)]
    locked = sorted((i for i in invs if i.status == InvStatus.LOCKED), key=lambda i: (i.approved_at, i.id))
    retired = sorted((i for i in invs if i.status == InvStatus.SUPERSEDED), key=lambda i: (i.created_at, i.id))
    dead = sorted(
        (d for d in store.load_all("de") if isinstance(d, DeadEnd) and d.status == "ACTIVE"),
        key=lambda d: (d.created_at, d.id),
    )
    return locked, retired, dead, sum(1 for i in invs if i.status == InvStatus.PROPOSED)


def counts(store: Store) -> Counts:
    locked, retired, dead, proposed = _load(store)
    return Counts(len(locked), len(retired), len(dead), proposed)


def _rule(store: Store, inv: Invariant, replaced: list[Invariant]) -> list[str]:
    assert inv.approved_at is not None  # LOCKED records always carry it (models.py)
    lines = [f"#### {_flat(inv.title)}", "", inv.assertion.strip(), ""]
    lines.append(f"- **Applies to:** {_paths(list(inv.scope.paths))}")
    when = inv.approved_at.date().isoformat()
    lines.append(f"- **Approved by:** {_name(inv.approved_by)}, {when}, {VIA.get(inv.decided_via, 'in the terminal')}")
    lines.append(f"- **Test:** `{inv.verification.harness_path}` ({inv.verification.runner})")
    problem = verifier.check_integrity(store.root, inv)
    if problem:  # "inv_x: harness modified since approval": the spec must not claim a test that isn't there
        lines.append(f"- **Problem:** {problem.partition(': ')[2] or problem}")
    for old in replaced:
        lines.append(f"- **Replaces:** {_flat(old.title)} (`{old.id}`)")
    if inv.adr_id:
        try:
            record = adr.get(store, inv.adr_id)
            lines.append(f"- **Decision record:** {_flat(record.title)} (`{inv.adr_id}`)")
        except (KeyError, adr.AdrError, OSError, ValueError):
            lines.append(f"- **Decision record:** `{inv.adr_id}`")
    lines.append(f"- **Id:** `{inv.id}`")
    return lines


def render(store: Store, generated_line: bool = False) -> str:
    """The whole document as Markdown. `generated_line`: for a written copy."""
    locked, retired, dead, _proposed = _load(store)
    titles = {i.id: _flat(i.title) for i in [*locked, *retired]}
    out: list[str] = [GENERATED, ""] if generated_line else []
    out += [TITLE, ""]
    if not locked:
        out += ["No rules have been approved yet.", ""]
    else:
        out += [
            f"{_n(len(locked), 'rule')} in force. A person approved each one, and each has a test that must "
            "keep passing. This document is generated from the SeamSpec ledger: it lists what was approved, "
            "and nothing else.",
            "",
            "## Rules in force",
            "",
        ]
        for name, rules in _by_area(store, locked):
            out += [f"### `{name}` ({_n(len(rules), 'rule')})", ""]
            for inv in rules:
                out += [*_rule(store, inv, [o for o in retired if o.superseded_by == inv.id]), ""]

    if retired:
        out += ["## Retired rules", "", "These were approved once and are no longer checked.", ""]
        for inv in retired:
            by = inv.superseded_by
            after = f"Replaced by {titles[by]} (`{by}`)." if by in titles else (
                f"Replaced by `{by}`, which is not in force." if by else "Not replaced.")  # fmt: skip
            out += [
                f"- **{_flat(inv.title)}** (`{inv.id}`): {_flat(inv.assertion)}",
                f"  - Retired because: {_flat(inv.status_reason or 'no reason recorded')}",
                f"  - {after}",
            ]
        out.append("")

    if dead:
        out += ["## Tried and failed", "",
                "Approaches that were tried and did not work. They carry no test; they are here so nobody "
                "repeats them without knowing why they failed.", ""]  # fmt: skip
        for name, items in _by_area(store, dead):
            out += [f"### `{name}`", ""]
            for de in items:
                out += [
                    f"- **Tried:** {_flat(de.approach)}",
                    f"  - **Why it failed:** {_flat(de.failure_symptom)}",
                    f"  - Applies to {_paths(list(de.scope.paths))} · recorded {de.created_at.date().isoformat()}"
                    f" · `{de.id}`",
                ]
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def is_generated(text: str) -> bool:
    """Was this file written by `seamspec spec --out`? Only such a file may be overwritten."""
    return text.lstrip("﻿").startswith(GENERATED_PREFIX)
