"""Workflow command templates, rendered per host (SPEC §15A).

One template per command in `seamspec/templates/commands/<name>.md` (frontmatter + body with
`{{args}}`), plus a shared `_footer.md`. v0.1 renders them as Claude Code plugin skills
(`seamspec-plugin/skills/<name>/SKILL.md`, invoked as `/seamspec:<name>`), plus the plugin's
agents from `seamspec/templates/agents/` (`seamspec-plugin/agents/<name>.md`). Other hosts' renderings
follow with their adapters.
"""

from __future__ import annotations

import json
from importlib.resources import files
from pathlib import Path

V01_COMMANDS = ("lock", "dead-end", "supersede", "checkpoint", "context", "status", "explain", "drain")
# Plugin agents (ADR-20261013-b7d2): SeamSpec's reviewer, a separate read-only agent that explains
# what is waiting for review. Rendered as `seamspec-plugin/agents/<name>.md`, used as `seamspec:<name>`.
V01_AGENTS = ("reviewer",)
CLAUDE_ARGS = "$ARGUMENTS"


def _template(name: str) -> str:
    return files("seamspec.templates").joinpath("commands", f"{name}.md").read_text("utf-8")


OTHER_HOSTS = ("cursor", "vscode", "antigravity")  # ADR-20261013-e8f3
# Where each host keeps a project command, and how the user invokes it.
HOST_FILES = {
    "cursor": ".cursor/commands/seamspec-{name}.md",  # /seamspec-<name>
    "vscode": ".github/prompts/seamspec-{name}.prompt.md",  # /seamspec-<name>
    "antigravity": ".agents/skills/seamspec-{name}/SKILL.md",  # /seamspec-<name>
}
# The reviewer is a separate, read-only agent (ADR-20261013-b7d2). Claude Code ships it in the plugin;
# VS Code and Antigravity get it as a custom agent (ADR-20261015-4f7b), and Cursor as a read-only
# subagent that reads the ledger itself, like Antigravity's (ADR-20261018-9c4d).
REVIEWER_HOSTS = ("cursor", "vscode", "antigravity")
NEEDS_REVIEWER = ("explain",)
AGENT_FILES = {
    "vscode": ".github/agents/seamspec-{name}.agent.md",  # picked by /seamspec-explain (prompt file `agent:`)
    "antigravity": ".agents/agents/seamspec-{name}.md",  # started by the main agent with invoke_subagent
    "cursor": ".cursor/agents/seamspec-{name}.md",  # started by the main agent, or typed as /seamspec-reviewer
}
REVIEWER_LINES = (  # sentences that point at the reviewer; other hosts don't have it
    ("   Offer an explanation from SeamSpec's reviewer, a separate agent that didn't write the test\n"
     "   (`/seamspec:explain`), and offer to open the review for them:", "   Offer to open the review for them:"),
    (";\n   offer an explanation from SeamSpec's reviewer (`/seamspec:explain`) first.", "."),
)  # fmt: skip


def has_reviewer(host: str) -> bool:
    return host == "claude" or host in REVIEWER_HOSTS


def commands_for(host: str) -> tuple[str, ...]:
    return V01_COMMANDS if has_reviewer(host) else tuple(n for n in V01_COMMANDS if n not in NEEDS_REVIEWER)


def _for_other_hosts(text: str, host: str) -> str:
    if not has_reviewer(host):
        for old, new in REVIEWER_LINES:
            text = text.replace(old, new)
        if "/seamspec:explain" in text:
            raise ValueError("a command template points at /seamspec:explain: update REVIEWER_LINES")
    return text.replace("/seamspec:", "/seamspec-")


def render(name: str, host: str = "claude") -> str:
    """The full file for one command on one host."""
    if host != "claude":
        return _render_other(name, host)
    text = _template(name)
    if not text.startswith("---\n"):
        raise ValueError(f"template {name!r} has no frontmatter")
    front, body = text[4:].split("\n---\n", 1)
    header = f'<!-- Generated by seamspec from template "{name}". Edit seamspec/templates/commands/{name}.md and run `python -m seamspec.core.commands`. -->'  # noqa: E501
    body = body.replace("{{args}}", CLAUDE_ARGS).strip()
    footer = _template("_footer").strip()
    return f"---\n{front.strip()}\n---\n{header}\n\n{body}\n\n{footer}\n"


def _render_other(name: str, host: str) -> str:
    """Cursor: a plain Markdown command. VS Code: a prompt file. Antigravity: a skill."""
    if host not in OTHER_HOSTS:
        raise ValueError(f"unknown host {host!r}")
    if name in NEEDS_REVIEWER and not has_reviewer(host):
        raise ValueError(f"{name!r} needs SeamSpec's reviewer, which {host} doesn't have")
    text = _template(name)
    front, body = text[4:].split("\n---\n", 1)
    meta = dict(line.split(": ", 1) for line in front.strip().splitlines() if ": " in line)
    description = meta.get("description", "").strip()
    args = "anything the user typed after the command"
    if name in NEEDS_REVIEWER:  # how the reviewer is reached differs per host
        body = _template(f"_{name}-{host}")
    body = _for_other_hosts(body.replace("{{args}}", args).strip(), host)
    footer = _for_other_hosts(_template("_footer").strip(), host)
    header = f'<!-- Generated by seamspec from template "{name}" for {host}. Rerun `seamspec init` to update it. -->'
    if host == "cursor":
        return f"{header}\n\n{body}\n\n{footer}\n"
    if host == "vscode":
        hint = meta.get("argument-hint", "").strip()
        if name in NEEDS_REVIEWER:  # runs in the reviewer itself: its answer reaches the user unrelayed
            hint = meta.get("argument-hint", "").strip()
            lines = ["---", f"description: {json.dumps(description)}", "agent: seamspec-reviewer",
                     *([f"argument-hint: {json.dumps(hint.strip(chr(34)))}"] if hint else []), "---"]  # fmt: skip
            return "\n".join(lines) + f"\n{header}\n\n{body}\n"
        lines = [
            "---",
            f"description: {json.dumps(description)}",
            "agent: agent",
            *([f"argument-hint: {json.dumps(hint.strip(chr(34)))}"] if hint else []),
            "---",
        ]
        return "\n".join(lines) + f"\n{header}\n\n{body}\n\n{footer}\n"
    return f"---\nname: seamspec-{name}\ndescription: {json.dumps(description)}\n---\n{header}\n\n{body}\n\n{footer}\n"


def render_agent(name: str, host: str = "claude") -> str:
    """An agent definition: for Claude Code the plugin's (the template's frontmatter); for VS Code and
    Antigravity a custom agent with only read and search tools (ADR-20261015-4f7b). Then its prompt."""
    if not has_reviewer(host):
        raise ValueError(f"host {host!r}: SeamSpec's reviewer can't be made read-only there yet")
    text = files("seamspec.templates").joinpath("agents", f"{name}.md").read_text("utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"agent template {name!r} has no frontmatter")
    front, body = text[4:].split("\n---\n", 1)
    if host == "claude":
        header = f'<!-- Generated by seamspec from template "{name}". Edit seamspec/templates/agents/{name}.md and run `python -m seamspec.core.commands`. -->'  # noqa: E501
        return f"---\n{front.strip()}\n---\n{header}\n\n{body.strip()}\n"
    meta = dict(line.split(": ", 1) for line in front.strip().splitlines() if ": " in line)
    description = json.dumps(meta.get("description", "").strip())
    if host == "vscode":
        # `seamspec/review_material` is the one SeamSpec tool it gets; VS Code ignores a tool it can't find,
        # and the prompt then says how to find the items with read and search alone.
        lines = [f"name: seamspec-{name}", f"description: {description}",
                 "tools: ['read', 'search', 'seamspec/review_material']", "agents: []"]  # fmt: skip
    elif host == "cursor":
        # `readonly` blocks file edits and state-changing shell commands; Cursor has no tool allowlist.
        lines = [f"name: seamspec-{name}", f"description: {description}", "model: inherit", "readonly: true"]
    else:
        # Antigravity's docs name no MCP tool for an allowlist, and warn that a wrong name can hang the
        # subagent: it gets the two documented read tools, no commands, and reads the ledger itself.
        lines = [f"name: seamspec-{name}", f"description: {description}", "tools:", "  - view_file",
                 "  - grep_search", "mainAgent: false", "subagent: true", 'commandExecutionPolicy: "off"']  # fmt: skip
    header = f'<!-- Generated by seamspec from template "{name}" for {host}. Rerun `seamspec init` to update it. -->'
    return "---\n" + "\n".join(lines) + f"\n---\n{header}\n\n{body.strip()}\n"


def write_plugin_skills(plugin_dir: Path) -> list[Path]:
    """(Re)generate the plugin's skills from the templates."""
    written = []
    for name in V01_COMMANDS:
        path = plugin_dir / "skills" / name / "SKILL.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(name), encoding="utf-8")
        written.append(path)
    for name in V01_AGENTS:
        path = plugin_dir / "agents" / f"{name}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render_agent(name), encoding="utf-8")
        written.append(path)
    return written


if __name__ == "__main__":  # python -m seamspec.core.commands  (from the repo root)
    for p in write_plugin_skills(Path("seamspec-plugin")):
        print(f"wrote {p}")
