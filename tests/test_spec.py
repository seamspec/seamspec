"""`seamspec spec`: the spec the code has earned, generated from the ledger (SPEC §15.2)."""

from __future__ import annotations

from pathlib import Path

import pytest
from typer.testing import CliRunner

from seamspec.cli import app
from seamspec.core import lifecycle, specdoc
from seamspec.core.config import load_config
from seamspec.core.store import Store

from .test_lifecycle import PASS, propose

runner = CliRunner()


@pytest.fixture
def in_repo(git_repo: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    monkeypatch.setenv("SEAMSPEC_ALLOW_NONINTERACTIVE_APPROVE", "1")
    monkeypatch.chdir(git_repo)
    return git_repo


def ledger(root: Path) -> dict[str, str]:
    """Two rules in force (one replaced an older rule), one proposed, one rejected, one dead end."""
    store, cfg = Store(root), load_config(root)
    old = propose(root)["id"]
    lifecycle.approve(store, cfg, old)
    new = propose(root, title="Retry delay is capped at 60s", assertion="Retry delay never exceeds 60 seconds.")["id"]
    lifecycle.approve(store, cfg, new)
    lifecycle.supersede(store, cfg, old, reason="Batch jobs need a longer wait.", replacement_id=new)
    other = propose(root, title="Docs build", assertion="The docs always build.", scope_paths=["docs/**"])["id"]
    lifecycle.approve(store, cfg, other)
    waiting = propose(root, title="Still waiting", assertion="Proposed and not approved yet.")["id"]
    refused = propose(root, title="Refused idea", assertion="Rejected by the reviewer, never in force.")["id"]
    lifecycle.reject(store, cfg, refused, "not wanted")
    dead = lifecycle.log_dead_end(
        store, cfg, scope_paths=["src/queue*"], approach="Sleeping in a loop\ninstead of backing off.",
        failure_symptom="The queue stalled\nunder load.",
    )["id"]  # fmt: skip
    return {"old": old, "new": new, "other": other, "waiting": waiting, "refused": refused, "dead": dead}


def test_the_spec_lists_what_was_approved_and_nothing_else(in_repo: Path) -> None:
    ids = ledger(in_repo)
    text = specdoc.render(Store(in_repo))
    order = [
        "# Spec: what this code guarantees",
        "2 rules in force. A person approved each one, and each has a test that must keep passing.",
        "## Rules in force",
        "### `docs` (1 rule)",
        "#### Docs build",
        "### `src` (1 rule)",
        "#### Retry delay is capped at 60s",
        "Retry delay never exceeds 60 seconds.",
        "- **Applies to:** `src/queue*`",
        "- **Approved by:** Maya Rao, ",
        f"- **Test:** `.seamspec/tests/test_{ids['new']}.py` (pytest)",
        f"- **Replaces:** Retry delay is capped (`{ids['old']}`)",
        f"- **Id:** `{ids['new']}`",
        "## Retired rules",
        f"- **Retry delay is capped** (`{ids['old']}`): Retry delay never exceeds 30 seconds.",
        "  - Retired because: Batch jobs need a longer wait.",
        f"  - Replaced by Retry delay is capped at 60s (`{ids['new']}`).",
        "## Tried and failed",
        "- **Tried:** Sleeping in a loop instead of backing off.",  # one line, whatever the record's line breaks
        "  - **Why it failed:** The queue stalled under load.",
        f"`{ids['dead']}`",
    ]
    at = 0
    for part in order:  # each part appears after the one before it
        assert part in text[at:], f"missing or out of order: {part!r}\n{text}"
        at = text.index(part, at) + len(part)
    # Only what a human approved: nothing proposed, nothing rejected.
    for absent in (ids["waiting"], ids["refused"], "Still waiting", "Refused idea", "proposed"):
        assert absent not in text
    assert "maya@example.com" not in text and ", in the terminal" in text  # a name, never an email address
    assert specdoc.counts(Store(in_repo)) == specdoc.Counts(rules=2, retired=1, dead_ends=1, proposed=1)


def test_the_same_ledger_always_gives_the_same_bytes(in_repo: Path) -> None:
    ledger(in_repo)
    first = specdoc.render(Store(in_repo), generated_line=True)
    assert first == specdoc.render(Store(in_repo), generated_line=True)
    assert first.startswith(specdoc.GENERATED + "\n\n# Spec") and first.endswith("\n") and not first.endswith("\n\n")
    assert specdoc.is_generated(first) and not specdoc.is_generated(specdoc.render(Store(in_repo)))


def test_an_empty_ledger_says_so(in_repo: Path) -> None:
    out = runner.invoke(app, ["spec"])
    assert out.exit_code == 0 and "No rules have been approved yet." in out.output
    assert "## Rules in force" not in out.output and "Generated by" not in out.output


def test_a_rule_whose_test_was_changed_is_marked(in_repo: Path) -> None:
    """The spec says every rule has a test; it must not say so about a test that was edited or removed."""
    store, cfg = Store(in_repo), load_config(in_repo)
    inv_id = propose(in_repo)["id"]
    lifecycle.approve(store, cfg, inv_id)
    assert "**Problem:**" not in specdoc.render(store)
    (in_repo / f".seamspec/tests/test_{inv_id}.py").write_text(PASS + "# edited\n")
    assert "- **Problem:** harness modified since approval" in specdoc.render(store)


def test_printing_keeps_the_waiting_count_out_of_the_document(in_repo: Path) -> None:
    ledger(in_repo)
    out = runner.invoke(app, ["spec"])
    assert out.exit_code == 0, out.output
    assert out.output.startswith("# Spec: what this code guarantees")
    assert "Not in the spec: 1 proposed rule waiting for review (`seamspec review`)." in out.output
    assert "Not in the spec" not in specdoc.render(Store(in_repo), generated_line=True)


def test_out_writes_a_marked_copy_and_check_catches_drift(in_repo: Path) -> None:
    ids = ledger(in_repo)
    store, cfg = Store(in_repo), load_config(in_repo)
    wrote = runner.invoke(app, ["spec", "--out", "docs/RULES.md"])
    assert wrote.exit_code == 0, wrote.output
    assert "Wrote docs/RULES.md: 2 rules in force, 1 retired, 1 tried and failed." in wrote.output
    written = (in_repo / "docs/RULES.md").read_text()
    assert written == specdoc.render(store, generated_line=True)
    ok = runner.invoke(app, ["spec", "--check", "docs/RULES.md"])
    assert ok.exit_code == 0 and "docs/RULES.md is up to date" in ok.output

    # A new proposal is not part of the spec, so a committed copy doesn't go stale every time the agent proposes.
    propose(in_repo, title="Another idea", assertion="Something else that is only proposed.")
    assert runner.invoke(app, ["spec", "--check", "docs/RULES.md"]).exit_code == 0

    lifecycle.approve(store, cfg, ids["waiting"])
    stale = runner.invoke(app, ["spec", "--check", "docs/RULES.md"])
    assert stale.exit_code == 1 and "is out of date: run `seamspec spec --out docs/RULES.md`" in stale.output
    assert (in_repo / "docs/RULES.md").read_text() == written  # --check never writes
    assert runner.invoke(app, ["spec", "--out", "docs/RULES.md"]).exit_code == 0  # its own file: overwritten
    assert runner.invoke(app, ["spec", "--check", "docs/RULES.md"]).exit_code == 0
    (in_repo / "docs/RULES.md").write_bytes((in_repo / "docs/RULES.md").read_bytes().replace(b"\n", b"\r\n"))
    assert runner.invoke(app, ["spec", "--check", "docs/RULES.md"]).exit_code == 0  # Windows line endings


def test_out_never_overwrites_a_file_it_did_not_write(in_repo: Path) -> None:
    ledger(in_repo)
    (in_repo / "README.md").write_text("# My project\n")
    refused = runner.invoke(app, ["spec", "--out", "README.md"])
    assert refused.exit_code == 1 and "wasn't written by `seamspec spec`, so it is left alone" in refused.output
    assert (in_repo / "README.md").read_text() == "# My project\n"
    inside = runner.invoke(app, ["spec", "--out", ".seamspec/SPEC.md"])
    assert inside.exit_code == 1 and "can't be written inside .seamspec/" in inside.output
    assert not (in_repo / ".seamspec/SPEC.md").exists()
    folder = runner.invoke(app, ["spec", "--out", "src"])
    assert folder.exit_code == 1 and "is a folder" in folder.output
    both = runner.invoke(app, ["spec", "--out", "a.md", "--check", "a.md"])
    assert both.exit_code == 1 and "not both" in both.output and not (in_repo / "a.md").exists()
    missing = runner.invoke(app, ["spec", "--check", "nope.md"])
    assert missing.exit_code == 1 and "seamspec spec --out nope.md" in missing.output
